import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { normalizePath, type Plugin } from 'vite'
import { iconComponent, iconComponents } from './svg-components'

const root = fileURLToPath(new URL('../', import.meta.url))
const directories = ['src/components', 'src/views']
const componentName = (name: string) => name.replace(/(^|-)([a-z0-9])/gi, (_, _prefix, char) => char.toUpperCase())

function componentPaths() {
  const paths = new Map<string, string>()
  for (const directory of directories) {
    for (const file of readdirSync(resolve(root, directory), { recursive: true }).sort()) {
      if (!file.endsWith('.vue')) continue
      const name = componentName(basename(file, '.vue'))
      const path = normalizePath(`${directory}/${file}`)
      if (paths.has(name)) throw new Error(`Duplicate component name: ${name}`)
      paths.set(name, path)
    }
  }
  return paths
}

function writeTypes(paths: Map<string, string>) {
  const types = new Map([...paths].map(([name, path]) => [name, "./" + path]))
  for (const [tag, icon] of iconComponents) types.set(componentName(tag), "~icons/" + icon)
  const members = [...types].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([name, path]) => {
    const key = name.includes(':') ? "'" + name + "'" : name
    return "    " + key + ": typeof import('" + path + "')['default']"
  })
  for (const name of ['RouterLink', 'RouterView']) {
    members.push("    " + name + ": typeof import('vue-router')['" + name + "']")
  }
  const file = resolve(root, 'components.d.ts')
  const source = [
    '// Generated by build-support/component-imports.ts',
    'export {}',
    '',
    "declare module 'vue' {",
    '  export interface GlobalComponents {',
    ...members,
    '  }',
    '}',
    '',
  ].join('\n')
  if (!existsSync(file) || readFileSync(file, 'utf8') !== source) writeFileSync(file, source)
}

export function componentImports(): Plugin {
  let paths = componentPaths()
  return {
    name: 'plain-component-imports',
    enforce: 'post',
    buildStart() {
      writeTypes(paths)
    },
    configureServer({ watcher }) {
      const refresh = (file: string) => {
        const path = normalizePath(relative(root, file))
        if (path.endsWith('.vue') && directories.some(dir => path.startsWith(dir + '/'))) {
          paths = componentPaths()
          writeTypes(paths)
        }
      }
      watcher.on('add', refresh).on('unlink', refresh)
    },
    transform(code, id) {
      const [file, query] = id.split('?')
      if (!file.endsWith('.vue') || (query && !/(^|&)type=(script|template)(&|$)/.test(query))) return
      const imports = new Map<string, string>()
      const transformed = code.replace(
        /^(\s*const _component_[\w$]+ = )_resolveComponent\("([^"\\]+)"\)/gm,
        (match, prefix: string, tag: string) => {
          const path = paths.get(componentName(tag))
          const source = iconComponent(tag) ?? (path && '/' + path)
          if (!source || (path && normalizePath(resolve(root, path)) === normalizePath(file))) return match
          let binding = imports.get(source)
          if (!binding) {
            binding = '__plain_component_' + imports.size
            imports.set(source, binding)
          }
          return prefix + binding
        },
      )
      if (imports.size) {
        const header = [...imports].reverse().map(([source, binding]) =>
          `import ${binding} from ${JSON.stringify(source)}`,
        ).join('\n')
        return header + '\n' + transformed
      }
    },
  }
}
