#[test]
fn shared_png_decode_keeps_pixels_formats_and_capture_dimensions() {
    for &(png, rgba) in CASES {
        assert!(png_payload_matches(png, 1, 1));
        assert!(!png_payload_matches(png, 2, 1));
        let decoded = plain_libs::image::load_from_memory_with_format(
            png,
            plain_libs::image::ImageFormat::Png,
        )
        .unwrap();
        assert_eq!(decoded.into_rgba8().as_raw(), &rgba);
    }
}

#[test]
fn shared_png_decode_rejects_crc_failures_truncation_and_non_png_input() {
    for &(png, _) in CASES {
        let mut corrupt = png.to_vec();
        corrupt[29] ^= 1;
        assert!(!png_payload_matches(&corrupt, 1, 1));
        assert!(!png_payload_matches(&png[..png.len() / 2], 1, 1));
    }
    assert!(!png_payload_matches(
        b"\xff\xd8\xffgenerated jpeg marker",
        1,
        1
    ));
}
